
import os
import re
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    KeepTogether
)


def clean_markdown(text):
    """Remove Markdown formatting symbols from complaint text."""
    text = re.sub(r"```.*?```", "", text, flags=re.DOTALL)
    text = re.sub(r"^\s*#{1,6}\s*", "", text, flags=re.MULTILINE)
    text = re.sub(r"\*\*(.*?)\*\*", r"\1", text)
    text = re.sub(r"__(.*?)__", r"\1", text)
    text = re.sub(r"(?<!\*)\*(?!\s)(.*?)(?<!\s)\*(?!\*)", r"\1", text)
    text = re.sub(r"(?<!_)_(?!\s)(.*?)(?<!\s)_(?!_)", r"\1", text)
    text = re.sub(r"^\s*[-*]\s+", "• ", text, flags=re.MULTILINE)
    return text.strip()


def generate_complaint_pdf(complaint_text, output_path):
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)

    complaint_text = clean_markdown(complaint_text)

    doc = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        rightMargin=17 * mm,
        leftMargin=17 * mm,
        topMargin=13 * mm,
        bottomMargin=13 * mm
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ComplaintTitle",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=15,
        alignment=TA_CENTER,
        textColor=colors.HexColor("#17365D"),
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        "ComplaintBody",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=10.5,
        spaceAfter=3,
        alignment=0
    )

    heading_style = ParagraphStyle(
        "ComplaintHeading",
        parent=body_style,
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=11,
        spaceBefore=4,
        spaceAfter=3,
        textColor=colors.HexColor("#17365D")
    )

    story = [
        Paragraph("SATYA - CONSUMER COMPLAINT DRAFT", title_style),
        Paragraph(
            "Draft generated by SATYA AI. Review all details and legal references "
            "before signing or submitting.",
            body_style
        ),
        Spacer(1, 5)
    ]

    for line in complaint_text.splitlines():
        line = line.strip()

        if not line:
            story.append(Spacer(1, 2))
            continue

        safe_line = escape(line)

        # Treat short all-caps lines as section headings.
        if len(line) < 100 and line.upper() == line and any(c.isalpha() for c in line):
            story.append(Paragraph(safe_line, heading_style))
        else:
            story.append(Paragraph(safe_line, body_style))

    # Keep the document within two pages.
    def check_page_limit(canvas, document):
        if canvas.getPageNumber() > 2:
            raise ValueError(
                "Complaint is longer than 2 pages. Shorten the complaint text."
            )

    doc.build(story)
    return output_path
